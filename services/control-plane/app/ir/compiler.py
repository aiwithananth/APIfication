"""Deterministic compiler: canonical spec → build artefact source tree.

Generated source is a *build artefact*. The CCS remains the source of truth
(section 26.5). Templates are deterministic, so the same revision always
produces the same digest.
"""
from __future__ import annotations

import hashlib
import json
import re

from ..models import CapabilitySpec
from .projections import graphql_sdl, mcp_tools, openapi, rego


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-") or "capability"


def compile_capability(spec_dict: dict, revision_number: int = 0) -> dict:
    spec = CapabilitySpec.model_validate(spec_dict)
    slug = _slug(spec.capability.name)
    files: dict[str, str] = {}

    files["ir.json"] = json.dumps(spec_dict, indent=2, sort_keys=True)
    files["contracts/openapi.json"] = json.dumps(openapi(spec_dict), indent=2)
    files["contracts/schema.graphql"] = graphql_sdl([spec_dict])
    files["contracts/mcp_tools.json"] = json.dumps(mcp_tools(spec_dict), indent=2)
    files["policy/policy.rego"] = rego(spec_dict)

    routes = []
    for op in spec.operations:
        for itf in op.interfaces:
            if itf.kind == "rest" and itf.enabled and itf.path and itf.method:
                fn = re.sub(r"\W", "_", op.id)
                routes.append(
                    f'@app.api_route("{itf.path}", methods=["{itf.method.upper()}"], operation_id="{op.id}")\n'
                    f"async def {fn}(request: Request):\n"
                    f'    """{op.name}. Scopes: {", ".join(op.required_scopes) or "-"}. Policy: {op.policy_ref}."""\n'
                    f'    return await runtime.handle(request, operation_id="{op.id}")\n'
                )
    files["service/main.py"] = (
        '"""Generated service for capability: ' + spec.capability.name + '.\n\n'
        "DO NOT EDIT. Regenerate from the canonical specification. Business logic is\n"
        "executed by the shared APIfication runtime so REST, GraphQL and MCP share one\n"
        'policy and connector path."""\n'
        "from fastapi import FastAPI, Request\n\n"
        "from apf_runtime import CapabilityRuntime\n\n"
        f'runtime = CapabilityRuntime.from_file("ir.json")\n'
        f'app = FastAPI(title="{spec.capability.name}", version="1.0.{revision_number}")\n'
        "app.add_middleware(runtime.auth_middleware)  # token validation + trusted context\n\n\n"
        + "\n\n".join(routes)
        + '\n\napp.mount("/graphql", runtime.graphql_app())\napp.mount("/mcp", runtime.mcp_app())\n'
    )

    tests = ["import os\n\nimport httpx\nimport pytest\n\nBASE = os.environ.get(\"APF_BASE_URL\", \"http://localhost:8000\")\n"
             "TOKENS = {k: os.environ.get(f\"APF_TOKEN_{k.upper()}\", \"\") for k in [\"allowed\", \"denied\"]}\n"]
    for t in spec.tests:
        op = next((o for o in spec.operations if o.id == t.operation_id), None)
        if not op:
            continue
        rest = next((i for i in op.interfaces if i.kind == "rest" and i.path), None)
        if not rest:
            continue
        path = rest.path
        for k, v in t.input.items():
            path = path.replace("{" + k + "}", str(v))
        fn = re.sub(r"\W", "_", t.id)
        tests.append(
            f"\n\ndef test_{fn}():\n"
            f'    """{t.name} [{t.category}]"""\n'
            f"    # principal: {json.dumps(t.principal)}\n"
            f'    r = httpx.request("{rest.method}", BASE + "{path}")\n'
            f"    assert r.status_code in (401, {t.expect_status})\n"
        )
    files["tests/test_generated.py"] = "".join(tests)

    files["Dockerfile"] = (
        "FROM python:3.12-slim\nWORKDIR /srv\nRUN pip install --no-cache-dir fastapi uvicorn apf-runtime\n"
        "COPY . .\nUSER 10001\nEXPOSE 8080\nCMD [\"uvicorn\", \"service.main:app\", \"--host\", \"0.0.0.0\", \"--port\", \"8080\"]\n"
    )
    files["deploy/kubernetes.yaml"] = f"""apiVersion: apps/v1
kind: Deployment
metadata:
  name: {slug}
  labels: {{app.kubernetes.io/part-of: apification, apf/capability: {spec.capability.id}}}
spec:
  replicas: 2
  selector: {{matchLabels: {{app: {slug}}}}}
  template:
    metadata: {{labels: {{app: {slug}}}}}
    spec:
      serviceAccountName: {slug}-runtime      # workload identity; secrets resolved at runtime
      securityContext: {{runAsNonRoot: true}}
      containers:
        - name: api
          image: registry.local/apf/{slug}:1.0.{revision_number}
          ports: [{{containerPort: 8080}}]
          resources: {{limits: {{cpu: "500m", memory: 512Mi}}}}
          env:
            - {{name: APF_POLICY_BUNDLE, value: "{spec.capability.id}"}}
"""
    files["README.md"] = (
        f"# {spec.capability.name}\n\n{spec.capability.description}\n\n"
        "Generated by APIfication from the canonical capability specification (`ir.json`).\n\n"
        "| Operation | Side effect | Scopes | Interfaces |\n|---|---|---|---|\n"
        + "\n".join(f"| {o.name} | {o.side_effect} | {', '.join(o.required_scopes)} | "
                    f"{', '.join(i.kind for i in o.interfaces if i.enabled)} |" for o in spec.operations)
        + "\n"
    )
    h = hashlib.sha256()
    for k in sorted(files):
        h.update(k.encode())
        h.update(files[k].encode())
    return {"files": files, "digest": "sha256:" + h.hexdigest(), "entrypoint": "service/main.py"}
